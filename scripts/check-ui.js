"use strict";
const fs=require('fs'),path=require('path'),assert=require('assert');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'app/index.html'),'utf8');
const css=fs.readFileSync(path.join(root,'app/pro-ui.css'),'utf8');
const js=fs.readFileSync(path.join(root,'app/pro-ui.js'),'utf8');
const required=['proTimeline','proViewer','proMediaPanel','proInspector','proTimelineSplitter','proToolsPane','proExportPane','canvas','desktopExport','export','tracks','mediaInput','audioInput'];
for(const id of required)assert(html.includes(`id="${id}"`),'Missing element: '+id);
for(const file of ['pro-ui.css','pro-ui.js','ultra.js'])assert(html.includes(`./${file}`),'Missing dependency: '+file);
assert(css.includes('grid-template-rows'),'Viewport grid missing');
assert(css.includes('overflow:auto'),'Scroll support missing');
assert(js.includes('setTab'),'Inspector tabs missing');
assert(html.includes('NOVA CUT 13.0'),'Wrong version');
assert(fs.existsSync(path.join(root,'native-renderer.js')),'Missing Windows renderer');
console.log('✓ 9.0 UI structure, tabs, timeline, and export controls are present');
