"use strict";
const finite=x=>Number.isFinite(Number(x))?Number(x):0;
const clamp=(x,a,b)=>Math.max(a,Math.min(b,x));
function segmentsToTimeline(segments,clip){
  const offset=Math.max(0,finite(clip.at)),sourceStart=Math.max(0,finite(clip.start));
  const sourceEnd=finite(clip.end),speed=clamp(finite(clip.speed)||1,.25,4);
  const maxDuration=Math.max(0,(sourceEnd-sourceStart)/speed);
  if(!Number.isFinite(maxDuration)||!maxDuration)return [];
  return (segments||[]).slice(0,3000).flatMap((s,i)=>{
    const text=String(s.text||'').replace(/[\r\n\t ]+/g,' ').trim().slice(0,500);
    const start=clamp(finite(s.start)/speed,0,maxDuration),end=clamp(finite(s.end)/speed,0,maxDuration);
    if(!text||!Number.isFinite(start)||!Number.isFinite(end)||end<=start)return [];
    return [{id:`auto101-${Date.now().toString(36)}-${i}-${Math.random().toString(36).slice(2,6)}`,text,start:offset+start,end:offset+end,
      x:50,y:83,size:46,color:'#ffffff',animation:'none',style:'box',autoGenerated:true,sourceClipId:clip.id}];
  });
}
function stamp(t){const ms=Math.max(0,Math.round(finite(t)*1000));return [Math.floor(ms/3600000),Math.floor(ms/60000)%60,Math.floor(ms/1000)%60].map(x=>String(x).padStart(2,'0')).join(':')+','+String(ms%1000).padStart(3,'0');}
function makeSrt(texts){return [...(texts||[])].filter(x=>x&&Number.isFinite(+x.start)&&Number.isFinite(+x.end)&&+x.end>+x.start&&String(x.text||'').trim()).slice(0,10000).sort((a,b)=>a.start-b.start).map((x,i)=>`${i+1}\r\n${stamp(x.start)} --> ${stamp(x.end)}\r\n${String(x.text).replace(/\r\n?/g,'\n').replace(/<[^>]*>/g,'').trim().slice(0,1500)}\r\n`).join('\r\n');}
module.exports={segmentsToTimeline,stamp,makeSrt};
